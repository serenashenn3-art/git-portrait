  // ---- Generate Article ----
  window.GP_ARTICLE = {
    generate: function(report, lang) {
      const t = TEMPLATES[lang] || TEMPLATES['en'];
      const d = report.data;
      const r = report.radar;
      const p = report.preferences || {};
      const projects = report.projects || [];

      // Helper: format list
      const formatList = (arr, max = 5) => {
        if (!arr || !arr.length) return '-';
        const limited = arr.slice(0, max);
        return limited.join(', ') + (arr.length > max ? '...' : '');
      };

      // Helper: get investment desc
      const getInvestmentDesc = (tier) => {
        const key = 'invest' + tier;
        return t.investment[key] || t.investment.c;
      };

      // Build article sections
      const sections = [];

      // Title
      sections.push(`# ${t.title.replace('{name}', d.name || d.login)}`);
      sections.push(`*${t.subtitle}*`);
      sections.push('');

      // Opening
      sections.push('---');
      t.opening.forEach(line => {
        sections.push(line.replace('{name}', d.name || d.login));
      });
      sections.push('');

      // Basic Info
      sections.push(`## ${t.basicInfo.title}`);
      t.basicInfo.content.forEach(line => {
        sections.push(line
          .replace('{login}', d.login || '-')
          .replace('{location}', d.location || '-')
          .replace('{followers}', d.followers || 0)
          .replace('{repos}', d.publicRepos || 0)
          .replace('{stars}', d.totalStars || 0)
        );
      });
      sections.push('');

      // Gender
      sections.push(`## ${t.genderAnalysis.title}`);
      const gender = report.gender || { guess: 'unknown', confidence: 0 };
      if (gender.guess === 'female') {
        sections.push(t.genderAnalysis.female.replace('{confidence}', Math.round(gender.confidence * 100)));
      } else if (gender.guess === 'male') {
        sections.push(t.genderAnalysis.male.replace('{confidence}', Math.round(gender.confidence * 100)));
      } else {
        sections.push(t.genderAnalysis.unknown);
      }
      sections.push('');

      // Tech Stack
      sections.push(`## ${t.techStack.title}`);
      sections.push(t.techStack.intro);
      sections.push(`- ${t.techStack.techList.replace('{tech}', formatList(p.tech))}`);
      sections.push(`- ${t.techStack.domains.replace('{domains}', formatList(p.domains))}`);
      sections.push(`- ${t.techStack.tools.replace('{tools}', formatList(p.tools))}`);
      sections.push(`- ${t.techStack.style.replace('{style}', formatList(p.style))}`);
      sections.push('');

      // Radar
      sections.push(`## ${t.radarAnalysis.title}`);
      sections.push(t.radarAnalysis.intro.replace('{name}', d.name || d.login));
      sections.push(`- ${t.radarAnalysis.engineering.replace('{score}', r.engineering).replace('{desc}', t.engineering || 'README/Tests/License')}`);
      sections.push(`- ${t.radarAnalysis.innovation.replace('{score}', r.innovation).replace('{desc}', 'Innovation')}`);
      sections.push(`- ${t.radarAnalysis.completion.replace('{score}', r.completion).replace('{desc}', 'Completion')}`);
      sections.push(`- ${t.radarAnalysis.persistence.replace('{score}', r.persistence).replace('{desc}', 'Persistence')}`);
      sections.push(`- ${t.radarAnalysis.influence.replace('{score}', r.influence).replace('{desc}', 'Influence')}`);
      sections.push(`- ${t.radarAnalysis.doc.replace('{score}', r.doc).replace('{desc}', 'Documentation')}`);
      sections.push('');
      sections.push(`**${t.radarAnalysis.summary.replace('{overall}', report.overall).replace('{tier}', report.tier.t)}**`);
      sections.push('');

      // Projects
      if (projects.length > 0) {
        sections.push(`## ${t.projectAnalysis.title}`);
        sections.push(t.projectAnalysis.intro.replace('{count}', projects.length));

        // Top 3 projects
        const topProjects = projects.slice(0, 3);
        topProjects.forEach(proj => {
          sections.push(`- ${t.projectAnalysis.project
            .replace('{name}', proj.name)
            .replace('{stars}', proj.stars || 0)
            .replace('{desc}', proj.desc || '-')
            .replace('{score}', proj.score.total)
          }`);
        });

        // Best project
        const bestProject = projects[0];
        sections.push('');
        sections.push(`**${t.projectAnalysis.topProject
          .replace('{name}', bestProject.name)
          .replace('{score}', bestProject.score.total)
        }**`);
        sections.push('');
      }

      // Nicknames
      if (report.nicks && report.nicks.length > 0) {
        sections.push(`## ${t.nickname.title}`);
        sections.push(t.nickname.intro);
        report.nicks.slice(0, 3).forEach(nick => {
          sections.push(`- **${t.nickname.nick.replace('{name}', nick.n).replace('{reason}', nick.r)}**`);
        });
        sections.push('');
      }

      // Investment
      sections.push(`## ${t.investment.title}`);
      sections.push(`**${t.investment.verdict.replace('{tier}', report.tier.t).replace('{value}', report.investment)}**`);
      sections.push(getInvestmentDesc(report.tier.t));
      sections.push('');

      // Value Analysis
      if (report.value) {
        sections.push(`## ${t.valueAnalysis.title}`);
        sections.push(`- ${t.valueAnalysis.commercial.replace('{score}', report.value.commercial.score).replace('{desc}', report.value.commercial.desc)}`);
        sections.push(`- ${t.valueAnalysis.technical.replace('{score}', report.value.technical.score).replace('{desc}', report.value.technical.desc)}`);
        sections.push('');
      }

      // Closing
      sections.push(`## ${t.closing.title}`);
      t.closing.content.forEach(line => {
        sections.push(line);
      });
      sections.push('');
      sections.push('---');
      sections.push('*Generated by GitPortrait - Fun & Useful GitHub Contributor Portrait*');
      sections.push(`*${d.login} · ${report.overall}/100 · ${report.tier.t}*`);

      return sections.join('\n');
    },

    getTemplates: function() {
      return Object.keys(TEMPLATES);
    }
  };

